    private void add_btnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_add_btnActionPerformed
        // TODO add your handling code here:
        
                try {
            String id = productid_fld.getText().trim();
            String name = Pname_fld.getText().trim();
            double price = Double.parseDouble(price_fld.getText());
            int qty = Integer.parseInt(quantity_fld.getText());
            
            if (id.isEmpty() || name.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Fill all fields!", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            Product p = new Product(id, name, price, qty);

            boolean success = controller.addProduct(p);

            if (success) {
                JOptionPane.showMessageDialog(this, "Product Added Successfully!");
                clearFields();
            } else {
                JOptionPane.showMessageDialog(this, "Failed to Add Product!", "Error", JOptionPane.ERROR_MESSAGE);
            }

        } catch (HeadlessException | NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Invalid Input: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
      
        
    }//GEN-LAST:event_add_btnActionPerformed

