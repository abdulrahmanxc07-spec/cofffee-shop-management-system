    private void search_btnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_search_btnActionPerformed
        // TODO add your handling code here:
        
         String id = search_fld.getText().trim();
        if (id.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Enter Product ID to Search!");
            return;
        }

        Product p = controller.searchProduct(id);

        if (p != null) {
            DefaultTableModel model = (DefaultTableModel) view_tbl.getModel();
            model.setRowCount(0); // clear table

            model.addRow(new Object[]{
                p.getProductId(),
                p.getProductName(),
                p.getPrice(),
                p.getQuantity(),
                
            });
        } else {
            JOptionPane.showMessageDialog(this, "Product Not Found!");
        }
                           
        
    }//GEN-LAST:event_search_btnActionPerformed

    private void view_btnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_view_btnActionPerformed
        // TODO add your handling code here:
    
      ArrayList<Product> list = controller.getAllProducts();

    DefaultTableModel model = (DefaultTableModel) view_tbl.getModel();
    model.setRowCount(0);

    for (Product p : list) {
        model.addRow(new Object[]{
            p.getProductId(),
            p.getProductName(),
            p.getPrice(),
            p.getQuantity(),
           
        });
    }
                                           
    }//GEN-LAST:event_view_btnActionPerformed

